/** Timed approach for each crucible sector. `at` is seconds after the briefing ends. */

export type WaveKind =
  | 'swarm'
  | 'wasp'
  | 'crawler'
  | 'crawler_pair'
  | 'jelly'
  | 'hornet'
  | 'nautilus'
  | 'centipede'
  | 'spitter'
  | 'pincer'
  /** Quick moth swarm burst. The engine also schedules these on its own. */
  | 'moths';

export interface WaveBeat {
  at: number;
  kind: WaveKind;
  /** 0 is the top of the lane, 1 is the bottom. Crawlers below 0.5 cling to the ceiling. */
  lane?: number;
}

export interface SectorDef {
  name: string;
  bossName: string;
  bossType: 'boss_centipede' | 'boss_brood' | 'boss_hive';
  bossHp: number;
  bossWidth: number;
  bossHeight: number;
  bossColor: string;
  /** Boss enters this long after the last beat. */
  breath: number;
  /** Failsafe if the script never finishes. */
  timeLimit: number;
  script: WaveBeat[];
}

